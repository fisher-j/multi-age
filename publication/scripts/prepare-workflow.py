"""Refresh the task index and browser-downloadable copies of linked repo files.

Run automatically before Quarto renders. Task metadata lives in tasks.json;
long-form review records live in task-*.qmd. No analytical pipeline is executed.
"""

import hashlib
import json
import re
import shutil
from pathlib import Path
from urllib.parse import unquote


PROJECT = Path(__file__).resolve().parents[1]
REPOSITORY = PROJECT.parent


def write_if_changed(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8", newline="\n")


def validate_tasks(tasks):
    ids = [task["id"] for task in tasks]
    if len(ids) != len(set(ids)):
        raise ValueError("Duplicate task IDs in tasks.json")
    owners = {}
    for task in tasks:
        for dependency in task.get("depends_on", []):
            if dependency not in ids or dependency == task["id"]:
                raise ValueError(f"{task['id']}: invalid dependency {dependency}")
        outputs = set(task.get("outputs", []))
        if outputs & set(task["files"]):
            raise ValueError(f"{task['id']}: outputs must be separate from maintained sources")
        if set(task.get("inputs", [])) & (set(task["files"]) | outputs):
            raise ValueError(f"{task['id']}: consumed inputs must be separate from maintained files")
        for path in outputs | set(task.get("private_outputs", [])):
            if path in owners:
                raise ValueError(f"Output has two owners: {path} ({owners[path]}, {task['id']})")
            owners[path] = task["id"]


def prepare():
    tasks = json.loads((PROJECT / "tasks.json").read_text(encoding="utf-8"))
    validate_tasks(tasks)

    index = [
        "---\ntitle: Task register and task list\nsidebar: workflow\nparams:\n  recompute:\n    value: []\n---\n",
        "<!-- Generated by scripts/prepare-workflow.py from tasks.json. -->\n",
        "The register links to the task entries below. Each entry summarizes the "
        "proposal or work recorded on its dedicated task page, with links to the "
        "full record and relevant review sections.\n",
        "```{r}\n#| label: publication-render-setup\n#| include: false\n"
        'source("scripts/task-execution.R")\npublication_setup(params$recompute)\n```\n',
        "## Task register {#task-register}\n",
        "| Order | Task | Status | Proposed target |\n|---:|---|---|---|",
    ]
    for order, task in enumerate(tasks):
        key = task["id"].lower()
        page = f"task-{key}.qmd"
        if not (PROJECT / page).is_file():
            raise FileNotFoundError(f"Missing dedicated task page: {page}")
        index.append(
            f"| {order} | [{task['id']} — {task['title']}](#{key}) | "
            f"{task['status']} | {task['target']} |"
        )

    index.append("\n## Task list {#task-list}\n")
    for task in tasks:
        key = task["id"].lower()
        page = f"task-{key}.qmd"
        index.extend([
            f"\n### [{task['id']} — {task['title']}]({page}) {{#{key}}}\n",
            f"**Status: {task['status']}.**\n",
            task["summary"] + "\n",
        ])
        write_if_changed(
            PROJECT / "_task-metadata" / f"{key}-status.qmd",
            f"<!-- Generated from tasks.json. -->\n\n"
            f"**Status: {task['status']}.** Working target: {task['target']}.\n",
        )
        files = [f"## Current repository files {{#{key}-files}}\n"]
        files.append(
            "Paths below are relative to the repository root. Downloads are refreshed "
            "from the local checkout on every render.\n"
        )
        files.append("<details>\n<summary>Browse current source files and outputs</summary>\n")
        if "outputs" in task:
            dependencies = task.get("depends_on", [])
            if dependencies:
                links = ", ".join(f"[{name}](task-{name.lower()}.qmd)" for name in dependencies)
                files.append(f"Upstream analytical records: {links}.\n")
            groups = [
                ("Maintained sources", task["files"]),
                ("Produced outputs", task["outputs"]),
                ("Consumed inputs and references", task.get("inputs", [])),
            ]
        else:
            groups = [(None, task["files"])]
        for title, paths in groups:
            if not paths:
                continue
            if title:
                files.append(f"\n### {title}\n")
            for path in paths:
                if path.lower().endswith((".rmd", ".qmd")):
                    if not (REPOSITORY / path).is_file():
                        raise FileNotFoundError(f"Repository source document is missing: {path}")
                    files.append(f"- `{path}`")
                else:
                    files.append(f"- [{path}](repo-files/{path})")
        files.append("\n</details>\n")
        files.append(f"\n[Back to this task in the task list](task-list.qmd#{key}).\n")
        write_if_changed(PROJECT / "_task-metadata" / f"{key}-files.qmd", "\n".join(files))
    write_if_changed(PROJECT / "task-list.qmd", "\n".join(index))

    # Only explicitly linked files are copied. Raw data and binary model objects
    # are not exposed by walking arbitrary source/output directories.
    paths = set()
    sources = [*PROJECT.glob("*.qmd"), *PROJECT.glob("sections/*.qmd"),
               *PROJECT.glob("_task-metadata/*.qmd")]
    for source in sources:
        paths.update(unquote(match) for match in re.findall(
            r"\]\(repo-files/([^\s)#]+)(?:#[^)]*)?\)",
            source.read_text(encoding="utf-8"),
        ))
    bundle = PROJECT / "repo-files"
    manifest = []
    for relative in sorted(paths - {"manifest.json"}):
        if Path(relative).is_absolute() or ".." in Path(relative).parts:
            raise ValueError(f"Repository download path must be relative without '..': {relative}")
        if relative.lower().endswith((".rmd", ".qmd", ".rmd.txt", ".qmd.txt")):
            raise ValueError(f"Analytical source documents are not published as downloads: {relative}")
        source = (REPOSITORY / relative).resolve()
        if not source.is_relative_to(REPOSITORY) or not source.is_file():
            raise FileNotFoundError(f"Linked repository file is missing or outside the repo: {relative}")
        destination = bundle / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, destination)
        manifest.append({"path": relative, "source": relative,
                         "sha256": hashlib.sha256(source.read_bytes()).hexdigest()})
    # Quarto may retain resources from earlier renders. Remove downloads whose
    # links were removed from the source, in both the input and published bundle.
    current = {item["path"] for item in manifest} | {"manifest.json"}
    # Recompute builds never prune canonical website downloads.
    import os
    directories = [bundle]
    if "recompute" not in os.getenv("QUARTO_PROFILE", "").split(","):
        directories.append(REPOSITORY / "docs/publication/repo-files")
        (REPOSITORY / "docs/publication/pipeline-fuel.html").unlink(missing_ok=True)
    for directory in directories:
        for path in directory.rglob("*"):
            if path.is_file() and path.relative_to(directory).as_posix() not in current:
                path.unlink()
    write_if_changed(bundle / "manifest.json", json.dumps(manifest, indent=2) + "\n")
    print(f"Prepared {len(tasks)} task summaries and {len(manifest)} current repository downloads.")


if __name__ == "__main__":
    prepare()
